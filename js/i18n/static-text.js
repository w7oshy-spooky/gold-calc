  function applyStaticText(doc, locale, dictionaries = DICTIONARIES) {
    const dictionary = dictionaries[locale];
    if (!dictionary) return 0;
    let applied = 0;

    doc.querySelectorAll('[data-t]').forEach((node) => {
      const key = node.getAttribute('data-t');
      if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
        node.textContent = dictionary[key];
        applied += 1;
      }
    });

    doc.querySelectorAll('[data-t-attr]').forEach((node) => {
      node.getAttribute('data-t-attr').split(';').forEach((pair) => {
        const [attribute, key] = pair.split(':');
        if (attribute && Object.prototype.hasOwnProperty.call(dictionary, key)) {
          node.setAttribute(attribute, dictionary[key]);
          applied += 1;
        }
      });
    });

    return applied;
  }

